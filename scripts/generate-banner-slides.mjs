/**
 * Generates the home hero slide list from `public/images/home-banner-slider/`.
 *
 * A browser cannot list a directory and the app is server-rendered, so the
 * folder is read here, at build time, and written out as a plain TypeScript
 * constant the component imports. Dropping a new image into the folder and
 * rebuilding (`npm start` / `npm run build` run this first) is all it takes to
 * add a slide — no code change.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, extname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** Web path, always forward slashes — it ends up in an `<img src>`. */
const FOLDER = 'images/home-banner-slider';
const SOURCE_DIR = join(root, 'public', 'images', 'home-banner-slider');
const OUT_FILE = join(root, 'src', 'app', 'components', 'home', 'home-banner-slides.ts');

const IMAGE_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.webp', '.avif', '.gif', '.svg']);

/** `banner-2.png` must come before `banner-10.png`, so compare digits as numbers. */
const naturally = new Intl.Collator('en', { numeric: true, sensitivity: 'base' }).compare;

/** Single-quoted literal, to match the repo's Prettier style. */
const quote = (value) => "'" + value.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'";

/** `large-pizza-zinger-deal.png` → `Large pizza zinger deal` — enough for an alt. */
function altFrom(file) {
  const words = file
    .slice(0, file.length - extname(file).length)
    .replace(/[-_]+/g, ' ')
    .trim();
  return words ? words.charAt(0).toUpperCase() + words.slice(1) : 'Gen Z Foods offer';
}

let files = [];
try {
  files = readdirSync(SOURCE_DIR, { withFileTypes: true })
    .filter((e) => e.isFile() && IMAGE_EXTENSIONS.has(extname(e.name).toLowerCase()))
    .map((e) => e.name)
    .sort(naturally);
} catch {
  // No folder yet: emit an empty list so the build still succeeds.
  console.warn(`[banner-slides] ${SOURCE_DIR} not found — writing an empty slide list.`);
}

const slides = files
  .map((f) => `  {\n    image: ${quote(`${FOLDER}/${f}`)},\n    alt: ${quote(altFrom(f))},\n  },`)
  .join('\n');

const contents = `// AUTO-GENERATED by scripts/generate-banner-slides.mjs — do not edit by hand.
// Add, rename or remove images in public/${FOLDER}/ and rebuild.

/** The banner artwork carries its own copy, so a slide is just the image. */
export interface HeroSlide {
  image: string;
  alt: string;
}

/** Every image in the slider folder, in natural filename order. */
export const HOME_BANNER_SLIDES: readonly HeroSlide[] = [
${slides}
];
`;

mkdirSync(dirname(OUT_FILE), { recursive: true });
let existing = null;
try {
  existing = readFileSync(OUT_FILE, 'utf8');
} catch {
  // First run — nothing to compare against.
}
// Only rewrite when something actually changed, so a watching build does not
// churn on every restart.
if (existing !== contents) writeFileSync(OUT_FILE, contents);
console.log(`[banner-slides] ${files.length} slide(s) from public/${FOLDER}/`);
